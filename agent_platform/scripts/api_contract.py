"""Generate frontend types from the actual FastAPI OpenAPI document.

This uses an in-memory, uninitialized application. It never reads deployment
settings, runs lifespan/migrations or connects to an upstream provider.
"""

import argparse
import json
from pathlib import Path

from agent_platform.apps.api.main import create_app
from agent_platform.infrastructure.config import Settings

OUTPUT = Path(__file__).resolve().parents[1] / "apps/web/src/api-contract.generated.ts"


def typescript(schema):
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[-1]
    for union in ("anyOf", "oneOf"):
        if union in schema:
            return " | ".join(typescript(item) for item in schema[union])
    if "allOf" in schema:
        return " & ".join(typescript(item) for item in schema["allOf"])
    if "enum" in schema:
        return " | ".join(
            json.dumps(value, ensure_ascii=False) for value in schema["enum"]
        )
    if "const" in schema:
        return json.dumps(schema["const"], ensure_ascii=False)
    kind = schema.get("type")
    if kind == "array":
        return f"Array<{typescript(schema['items'])}>"
    if kind == "object" or "properties" in schema:
        properties = schema.get("properties", {})
        if not properties:
            additional = schema.get("additionalProperties", True)
            if additional is False:
                return "Record<string, never>"
            return f"Record<string, {typescript(additional) if isinstance(additional, dict) else 'unknown'}>"
        required = schema.get("required", ())
        fields = [
            f"{json.dumps(key)}{'' if key in required else '?'}: {typescript(value)};"
            for key, value in sorted(properties.items())
        ]
        return "{ " + " ".join(fields) + " }"
    if kind in {"string", "boolean", "null"}:
        return kind
    if kind in {"number", "integer"}:
        return "number"
    if not schema or not kind:
        return "unknown"
    raise ValueError(f"Unsupported contract schema kind: {kind}")


def generate():
    app = create_app(Settings(database_url="sqlite:///:memory:"))
    try:
        document = app.openapi()
    finally:
        app.state.database.close()
    lines = [
        "// Generated by python -m agent_platform.scripts.api_contract. Do not edit.",
        "// Exact money is a JSON string. Optional fields may be omitted by permissions.",
        "",
    ]
    for name, schema in sorted(document["components"]["schemas"].items()):
        lines.append(f"export type {name} = {typescript(schema)};")
    lines += ["", "export type ApiResponseByOperation = {"]
    for path, methods in sorted(document["paths"].items()):
        for method, operation in sorted(methods.items()):
            if method not in {"get", "post", "patch", "put", "delete"}:
                continue
            responses = []
            for status, response in operation.get("responses", {}).items():
                if str(status).startswith("2"):
                    schema = (
                        response.get("content", {})
                        .get("application/json", {})
                        .get("schema")
                    )
                    if schema:
                        responses.append(typescript(schema))
            if responses:
                lines.append(
                    f"  {json.dumps(method.upper() + ' ' + path)}: {' | '.join(sorted(set(responses)))};"
                )
    lines += ["};", ""]
    return "\n".join(lines)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--output", type=Path, default=OUTPUT)
    args = parser.parse_args(argv)
    result = generate()
    if args.check:
        if not args.output.exists() or args.output.read_text() != result:
            print("API contract drift: regenerate and review api-contract.generated.ts")
            return 1
        print("API contract matches the current OpenAPI response/request schemas")
    else:
        args.output.write_text(result)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
