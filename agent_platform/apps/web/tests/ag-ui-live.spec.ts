import { expect, test } from "@playwright/test";
import { EventSchema } from "@ag-ui/core/schemas";

// Explicitly opt into the disposable smoke app; never log into a user's real
// deployment or invoke a paid model with fixture credentials.
test.skip(process.env.PLATFORM_AG_UI_SMOKE !== "1", "Requires tests.ag_ui_smoke_app on a separate loopback port");

test("真实前后端 AG-UI：工具调用、刷新恢复、取消和费用凭据", async ({ page, context }, info) => {
  const errors: string[] = [];
  page.on("pageerror", (error) => errors.push(error.message));
  const login = await context.request.post("/api/v1/auth/login", { data: { email: "ag-ui-browser@example.test", password: "temporary-platform-fixture-password" } });
  expect(login.status()).toBe(200);
  const auth = await login.json();
  const tenant = auth.user.memberships.find((item: { role: string }) => item.role === "owner").tenant_id as string;
  const root = `/api/v2/tenants/${tenant}`;
  await page.goto(`/#playground?tenant=${tenant}`);
  const agent = page.getByRole("combobox", { name: "当前 Agent", exact: true });
  await agent.click();
  await page.getByRole("option", { name: /AG-UI 联调助手/ }).click();
  const input = page.getByRole("textbox", { name: "发送给 Agent 的消息" });
  await input.fill("请计算 2+3");
  await input.press("Enter");
  await expect(page.getByText("计算结果是 5。", { exact: true })).toBeVisible();
  await expect(page.getByRole("button", { name: "停止生成" })).toHaveCount(0);
  await page.getByRole("button", { name: "运行详情", exact: true }).click();
  await expect(page.getByRole("dialog", { name: "运行详情" })).toContainText("正在调用：calculator");
  await expect(page.getByRole("dialog", { name: "运行详情" })).toContainText("工具已返回结果");
  await expect(page.getByRole("dialog", { name: "运行详情" })).toContainText("运行完成");
  await page.keyboard.press("Escape");
  const sessionId = new URLSearchParams(new URL(page.url()).hash.split("?")[1]).get("session");
  const sessionDetail = await (await context.request.get(`${root}/sessions/${sessionId}`)).json();
  const completedRun = sessionDetail.runs[0].id as string;
  const calls = await (await context.request.get(`${root}/usage/calls`)).json();
  const completedCalls = calls.items.filter((call: { run_id: string }) => call.run_id === completedRun);
  expect(completedCalls).toHaveLength(2);
  expect(completedCalls.every((call: { status: string }) => call.status === "confirmed")).toBe(true);
  const replay = await context.request.get(`${root}/runs/${completedRun}/ag-ui`);
  expect(replay.status()).toBe(200);
  expect(replay.headers()["x-ag-ui-protocol-version"]).toBe("1.0");
  const events = (await replay.text()).split("\n").filter((line) => line.startsWith("data: ")).map((line) => EventSchema.parse(JSON.parse(line.slice(6))));
  expect(events[0].type).toBe("RUN_STARTED");
  expect(events.at(-1)?.type).toBe("RUN_FINISHED");
  expect(events.some((event) => event.type === "TOOL_CALL_ARGS")).toBe(true);
  await input.fill("等待取消");
  await input.press("Enter");
  await expect(page.getByRole("article", { name: "Agent 正在回复" })).toContainText("正在等待取消。");
  const sessionUrl = page.url();
  await page.reload();
  await expect(page).toHaveURL(sessionUrl);
  await expect(page.getByRole("article", { name: "Agent 正在回复" })).toContainText("正在等待取消。");
  const resumedCalls = await (await context.request.get(`${root}/usage/calls`)).json();
  const resumedDetail = await (await context.request.get(`${root}/sessions/${sessionId}`)).json();
  const runIds = new Set(resumedDetail.runs.map((run: { id: string }) => run.id));
  expect(resumedCalls.items.filter((call: { run_id: string }) => runIds.has(call.run_id))).toHaveLength(3);
  await page.getByRole("button", { name: "停止生成" }).click();
  await expect(page.getByRole("button", { name: "停止生成" })).toHaveCount(0);
  const runs = await (await context.request.get(`${root}/runs`)).json();
  expect(runs.items[0].status).toBe("cancelled");
  await expect(input).toBeEnabled();
  await page.screenshot({ path: info.outputPath("ag-ui-real-frontend-backend.png"), fullPage: true });
  expect(errors).toEqual([]);
  await context.request.post("/api/v1/auth/logout", { headers: { "X-CSRF-Token": auth.csrf_token } });
});

test("内置可视化 Agent：交互、刷新、连续修改与窄屏", async ({ page, context }, info) => {
  const login = await context.request.post("/api/v1/auth/login", { data: { email: "ag-ui-browser@example.test", password: "temporary-platform-fixture-password" } });
  expect(login.status()).toBe(200);
  const auth = await login.json();
  const tenant = auth.user.memberships.find((item: { role: string }) => item.role === "owner").tenant_id as string;
  await page.goto(`/#playground?tenant=${tenant}`);
  await page.getByRole("combobox", { name: "当前 Agent", exact: true }).click();
  await page.getByRole("option", { name: /可视化界面助手/ }).click();
  const input = page.getByRole("textbox", { name: "发送给 Agent 的消息" });
  await input.fill("生成计数器界面");
  await input.press("Enter");
  const frames = page.locator('iframe[aria-label="生成的交互界面"]');
  await expect(frames).toHaveCount(1);
  const frame = page.frameLocator('iframe[aria-label="生成的交互界面"]').first();
  await frame.getByRole("button", { name: "增加" }).click();
  await expect(frame.locator("output")).toHaveText("1");
  expect(await frames.first().getAttribute("sandbox")).toBe("allow-scripts");
  await expect(page.getByRole("button", { name: "停止生成" })).toHaveCount(0);
  await page.reload();
  await expect(frames).toHaveCount(1);
  await frame.getByRole("button", { name: "增加" }).click();
  await expect(frame.locator("output")).toHaveText("1");
  await input.fill("修改计数器界面");
  await input.press("Enter");
  await expect(frames).toHaveCount(2);
  await expect(page.getByRole("button", { name: "停止生成" })).toHaveCount(0);
  await page.setViewportSize({ width: 390, height: 844 });
  await expect.poll(() => page.locator("#workspace-sidebar").evaluate((element) => element.getBoundingClientRect().right)).toBeLessThanOrEqual(0);
  await page.frameLocator('iframe[aria-label="生成的交互界面"]').last().getByRole("button", { name: "增加" }).click();
  await expect(page.frameLocator('iframe[aria-label="生成的交互界面"]').last().locator("output")).toHaveText("1");
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: info.outputPath("generative-ui-mobile.png"), fullPage: true });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await expect.poll(() => page.locator("#workspace-sidebar").evaluate((element) => element.getBoundingClientRect().left)).toBe(0);
  await page.screenshot({ path: info.outputPath("generative-ui-desktop.png"), fullPage: true });
  // Corrupt only this browser's read response, retaining the persisted version.
  await page.route("**/api/v2/tenants/*/sessions/*", async (route) => {
    if (route.request().method() !== "GET" || route.request().url().endsWith("/ag-ui")) return route.continue();
    const response = await route.fetch();
    const detail = await response.json();
    if (detail.artifacts?.length) detail.artifacts[detail.artifacts.length - 1].content.jsFunctions = 'throw new Error("初始化示例错误 <img src=x>")';
    await route.fulfill({ response, json: detail });
  });
  await page.reload();
  await expect(page.getByRole("alert").filter({ hasText: "生成的界面脚本执行失败" })).toBeVisible();
  await page.getByText("查看错误详情").click();
  await expect(page.getByText("初始化示例错误 <img src=x>", { exact: true })).toBeVisible();
  await expect(page.locator('iframe[aria-label="生成界面预览"]')).toHaveCount(1);
});

test("推理内容：实时展开、完成折叠、刷新恢复和思考中取消", async ({ page, context }, info) => {
  const errors: string[] = [];
  page.on("pageerror", (error) => errors.push(error.message));
  const login = await context.request.post("/api/v1/auth/login", { data: { email: "ag-ui-browser@example.test", password: "temporary-platform-fixture-password" } });
  expect(login.status()).toBe(200);
  const auth = await login.json();
  const tenant = auth.user.memberships.find((item: { role: string }) => item.role === "owner").tenant_id as string;
  const root = `/api/v2/tenants/${tenant}`;
  await page.goto(`/#playground?tenant=${tenant}`);
  await page.getByRole("combobox", { name: "当前 Agent", exact: true }).click();
  await page.getByRole("option", { name: /AG-UI 联调助手/ }).click();
  const input = page.getByRole("textbox", { name: "发送给 Agent 的消息" });
  await input.fill("展示思考");
  await input.press("Enter");
  // The short completed run may finish within one browser paint. Exercise
  // live visibility below with a reasoning phase held open until cancellation.
  await expect(page.getByRole("button", { name: "停止生成" })).toHaveCount(0);
  await expect(page.getByText("验证完成，结果为 300。", { exact: true })).toBeVisible();
  const completed = page.getByRole("region", { name: "思考过程", exact: true });
  await expect(completed).toHaveCount(1);
  await expect(completed.getByRole("button")).toHaveAttribute("aria-expanded", "false");
  await completed.getByRole("button").focus();
  await page.keyboard.press("Enter");
  await expect(completed.locator(".pg-reasoning-content")).toHaveText("先核对输入条件。再验证计算结果。");
  await page.reload();
  await expect(completed).toHaveCount(1);
  await completed.getByRole("button").click();
  await expect(completed.locator(".pg-reasoning-content")).toBeVisible();
  const sessionId = new URLSearchParams(new URL(page.url()).hash.split("?")[1]).get("session");
  await input.fill("展示思考，等待取消");
  await input.press("Enter");
  const thinking = page.getByRole("region", { name: "正在思考", exact: true });
  await expect(thinking).toContainText("再验证计算结果");
  const callsBefore = await (await context.request.get(`${root}/usage/calls`)).json();
  const detailBefore = await (await context.request.get(`${root}/sessions/${sessionId}`)).json();
  const runIds = new Set(detailBefore.runs.map((run: { id: string }) => run.id));
  const countBefore = callsBefore.items.filter((call: { run_id: string }) => runIds.has(call.run_id)).length;
  await page.reload();
  await expect(thinking).toContainText("再验证计算结果");
  const callsAfter = await (await context.request.get(`${root}/usage/calls`)).json();
  expect(callsAfter.items.filter((call: { run_id: string }) => runIds.has(call.run_id))).toHaveLength(countBefore);
  await page.getByRole("button", { name: "停止生成" }).click();
  await expect(page.getByRole("button", { name: "停止生成" })).toHaveCount(0);
  const interrupted = page.getByRole("region", { name: "思考已中断", exact: true });
  await expect(interrupted).toHaveCount(1);
  await interrupted.getByRole("button").click();
  await expect(interrupted.locator(".pg-reasoning-content")).toContainText("再验证计算结果");
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: info.outputPath("reasoning-mobile.png"), fullPage: true });
  await page.emulateMedia({ reducedMotion: "reduce" });
  await interrupted.getByRole("button").click();
  await expect(interrupted.getByRole("button")).toHaveAttribute("aria-expanded", "false");
  const detailAfter = await (await context.request.get(`${root}/sessions/${sessionId}`)).json();
  expect(detailAfter.reasoning.map((trace: { status: string }) => trace.status)).toEqual(["complete", "interrupted"]);
  await input.fill("展示思考，等待取消");
  await input.press("Enter");
  await expect(thinking).toContainText("再验证计算结果");
  // Starting another run replaces REST messages with AG-UI history. The
  // cancelled turn still needs its saved reasoning next to the user message.
  await expect(interrupted).toHaveCount(1);
  await page.getByRole("button", { name: "停止生成" }).click();
  await expect(page.getByRole("button", { name: "停止生成" })).toHaveCount(0);
  await expect(interrupted).toHaveCount(2);
  expect(errors).toEqual([]);
});
